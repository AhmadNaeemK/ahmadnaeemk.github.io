const GLYPHS = new Map<string, Glyph>(
  Object.entries(GLYPH_ROWS).map(([character, rows]) => [
    character,
    rows.split(" "),
  ]),
);
const BLANK: Glyph = GLYPHS.get(" ") ?? [];

/** Typographic marks the font draws through their plain equivalents. */
const PLAIN_EQUIVALENTS: Readonly<Record<string, string>> = {
  "‘": "'",
  "’": "'",
  "“": '"',
  "”": '"',
  "–": "-",
  "—": "-",
  "…": "...",
};

/** Text in the characters the font has: capitals, with marks and accents flattened. */
export function toBoardText(text: string): string {
  return text
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(
      /[‘’“”–—…]/gu,
      (character) => PLAIN_EQUIVALENTS[character] ?? character,
    )
    .toUpperCase();
}

/** A character the font lacks takes a space's width and draws nothing. */
export const glyphFor = (character: string): Glyph =>
  GLYPHS.get(character) ?? BLANK;

/** Width in pixels, with one pixel after every character. */
export function textWidth(text: string): number {
  let width = 0;
  for (const character of text) width += glyphFor(character)[0].length + 1;
  return width;
}
